            <section id="faq">
               <h2>Frequently Asked Questions</h2>
               <h3>What is the difference between journey orchestration and journey mapping?</h3>
               <p>
                  Journey mapping helps visualize the steps a customer might take based on assumptions or historical data. Journey
                  orchestration, on the other hand, adapts those journeys in real time by responding to actual behavior with context-aware actions across systems and channels.
               </p>
               <h3>How does a customer journey orchestration platform use AI?</h3>
               <p>
                  AI powers orchestration by predicting next-best actions, scoring lead quality, and dynamically adjusting message content, timing, and channel. This enables journeys to feel human, timely, and relevant without requiring manual input for every decision.
               </p>
               <h3>Do I need a CDP to implement journey orchestration?</h3>
               <p>
                  Not always, but it helps. A Customer Data Platform (CDP) unifies behavioral, transactional, and profile data into one place making it easier to personalize journeys in real time. Without it, orchestration relies on whatever data your CRM or systems can provide natively.
               </p>
               <h3>Can journey orchestration work across channels like WhatsApp, email, and voice?</h3>
               <p>
                  Yes. Modern orchestration platforms support omnichannel execution. That means a conversation can start via WhatsApp, `continue on SMS, and escalate to a live voice call while preserving context and compliance.
               </p>
               <h3>Is journey orchestration only for enterprise companies?</h3>
               <p>
                  No. While orchestration offers major advantages at scale, mid-market and even SMB teams, especially in healthcare,
                  education, staffing, and legal can benefit. Tools like Conversive are built specifically to make orchestration accessible,
                  with CRM-native design and vertical-ready templates.
